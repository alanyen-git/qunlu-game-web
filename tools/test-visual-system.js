#!/usr/bin/env node
"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const css=fs.readFileSync("assets/css/game.css","utf8");
const html=fs.readFileSync("index.html","utf8");
const sw=fs.readFileSync("sw.js","utf8");
const version=JSON.parse(fs.readFileSync("version.json","utf8"));
const marker=css.indexOf("VISUAL-SYSTEM-1.0");
assert(marker>=0,"visual system marker missing");
const visual=css.slice(marker);
assert.match(visual,/--vs-brass/);
assert.match(visual,/\.journey-hero/);
assert.match(visual,/\.mapscene-shell/);
assert.match(visual,/\.battlebox/);
assert.match(visual,/\.nav button\.active/);
assert.match(visual,/\.modal/);
assert.doesNotMatch(visual,/@keyframes|animation\s*:|transition\s*:/,"visual layer must remain static");
assert.match(html,/assets\/art\/qunlu-sigil\.svg/);
assert.match(html,/VISUAL-SYSTEM-1/);
assert.match(sw,/\.\/assets\/art\/qunlu-sigil\.svg/);
assert.equal(version.version,"CURRENT-2.25.10");
assert.equal(version.pwa_cache_revision,"v188");
assert.ok(version.changelog.some(x=>/VISUAL-SYSTEM-1\.0/.test(x)));
console.log(`Visual system regression OK: ${version.version}, static HUD/atlas/battle layer, PWA ${version.pwa_cache_revision}`);
