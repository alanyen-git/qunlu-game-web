"use strict";
const fs=require("node:fs");
const assert=require("node:assert/strict");
const source=fs.readFileSync("src/world-map-geopolitics-v1.js","utf8");
const version=JSON.parse(fs.readFileSync("version.json","utf8"));
const html=fs.readFileSync("index.html","utf8");
assert.match(source,/POLITY-PROVINCE-DEPTH-1\.0/);
const match=source.match(/const POLITY_PROVINCE_PAYLOAD=(\{.*?\});\nconst POLY_REGION_ALIASES/s);
assert.ok(match,"province payload must be embedded in world map module");
const payload=JSON.parse(match[1]);
assert.equal(payload.provinces.length,6,"Goldbalance must have six provinces");
assert.equal(payload.towns.length,8,"Goldbalance must have eight towns");
assert.equal(payload.wilds.length,12,"Goldbalance must have twelve wilderness maps");
assert.equal(payload.dungeons.length,8,"Goldbalance must have eight dungeons");
assert.equal(payload.npcs.length,18,"Goldbalance must have eighteen named NPCs");
const ids=rows=>{const all=rows.map(x=>x.id||x[0]);assert.equal(new Set(all).size,all.length,"duplicate IDs in province payload");return new Set(all)};
const provinceIds=ids(payload.provinces),townIds=ids(payload.towns),wildIds=ids(payload.wilds),dungeonIds=ids(payload.dungeons),npcIds=ids(payload.npcs);
for(const row of payload.towns)assert(provinceIds.has(row.province),"town province missing: "+row.id);
for(const row of payload.wilds)assert(provinceIds.has(row.province),"wild province missing: "+row.id);
for(const row of payload.dungeons)assert(provinceIds.has(row.province),"dungeon province missing: "+row.id);
for(const row of payload.npcs)assert(townIds.has(row.location_id),"NPC town missing: "+row.id);
assert.equal(new Set(payload.provinces.map(x=>x.identity)).size,payload.provinces.length,"province identities must be distinct");
assert.equal(new Set(payload.towns.map(x=>x.description)).size,payload.towns.length,"town descriptions must be distinct");
assert.equal(new Set(payload.wilds.map(x=>x.note)).size,payload.wilds.length,"wild descriptions must be distinct");
assert.equal(new Set(payload.dungeons.map(x=>x.note)).size,payload.dungeons.length,"dungeon descriptions must be distinct");
const active=["POL-001","POL-002","POL-003","POL-004","POL-007","POL-008","POL-009","POL-010","POL-011","POL-012","POL-013","POL-014","POL-015","POL-016","POL-019","POL-020"];
for(const id of active)for(const field of ["province_model","town_logic","wild_logic","dungeon_logic","npc_logic"])assert(payload.design[id]?.[field],"missing authored design axis: "+id+" / "+field);
assert.equal(version.version,"CURRENT-2.18.0");
assert.equal(version.polity_province_depth_revision,"POLITY-PROVINCE-DEPTH-1.0");
assert.equal(version.world_geopolitical_map_revision,"WORLD-MAP-GEOPOLITICS-1.8");
assert(html.includes("src/world-map-geopolitics-v1.js?v="+version.version));
console.log("polity province depth regression OK: 16 political design profiles, 6 provinces, 8 towns, 12 wilderness maps, 8 dungeons, 18 NPCs");
