"use strict";
const fs=require("node:fs");
const assert=require("node:assert/strict");
const css=fs.readFileSync("assets/css/game.css","utf8");
const runtime=fs.readFileSync("src/runtime.js","utf8");
const html=fs.readFileSync("index.html","utf8");
const sw=fs.readFileSync("sw.js","utf8");
const version=JSON.parse(fs.readFileSync("version.json","utf8"));
const marker="/* ===== CURRENT-2.12.1 BATTLE FORMATION V3 ===== */";
assert.ok(css.includes(marker),"missing current CSS");
const tail=css.slice(css.lastIndexOf(marker));
const rule=selector=>{
  const start=tail.indexOf(selector+"{");
  assert.ok(start>=0,"selector missing: "+selector);
  const brace=tail.indexOf("{",start);
  return tail.slice(brace+1,tail.indexOf("}",brace));
};
const double=/grid-template-columns:\s*repeat\(2,minmax\(0,1fr\)\)/;
assert.match(rule(".battle-formation-v2>.battle-allies"),double);
assert.match(tail.slice(tail.indexOf("@media(max-width:620px)")),double);
assert.match(tail.slice(tail.indexOf("@media(max-width:350px)")),double);
assert.match(rule(".battle-formation-v2>.battle-allies>.player"),/order:\s*0/);
assert.match(rule(".battle-formation-v2>.battle-allies>.companion"),/order:\s*1/);
assert.match(rule(".battle-formation-v2>.battle-allies>.companion"),/grid-column:\s*auto!important/);
assert.match(rule(".battle-formation-v2>.battle-allies>.party-mini"),/order:\s*2/);
assert.ok(!tail.includes("auto-fit"),"auto-fit would stretch last card");
assert.match(tail,/\.battle-formation-v2 \.companion-identity-depth-line\s*\{\s*display:none!important;/);
assert.match(tail,/\.battle-formation-v2 \.companion-aura-line,/);
assert.match(tail,/\.battle-formation-v2 \.companion-skill-line,/);
assert.match(runtime,/<div class="battle-allies">/);
assert.match(runtime,/<div class="battleunit player">/);
assert.match(runtime,/<div class="battleunit companion">/);
assert.match(runtime,/battleunit party-mini/);
assert.match(version.version,/^CURRENT-\d+\.\d+\.\d+$/);
assert.match(version.pwa_cache_revision,/^v\d+$/);
assert.ok(html.includes("assets/css/game.css?v="+version.version+"-BATTLE-FORMATION3"));
assert.ok(sw.includes('CACHE_PREFIX+"'+version.pwa_cache_revision+'"'));
console.log("battle formation regression OK");
